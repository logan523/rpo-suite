_MULTIREV_R1 = np.array([A_LEO_M, 0.0, 0.0])
_MULTIREV_R2 = np.array([0.0, 1.4 * A_LEO_M, 0.2 * A_LEO_M])


@pytest.mark.integration
@pytest.mark.parametrize("revolutions", [1, 2, 3])
@pytest.mark.parametrize("branch", ["low", "high"])
@pytest.mark.parametrize("time_factor", [1.05, 1.5, 2.5])
def test_multi_revolution_solutions_also_propagate_onto_the_target(
    revolutions, branch, time_factor
):
    """Both multi-revolution branches face the same oracle as the direct transfer."""
    tof = time_factor * minimum_multirev_time_s(
        _MULTIREV_R1, _MULTIREV_R2, MU, revolutions=revolutions
    )
    v1, _ = solve_lambert(
        _MULTIREV_R1, _MULTIREV_R2, tof, MU, revolutions=revolutions, branch=branch
    )
    arrival = propagate_two_body(
        np.concatenate([_MULTIREV_R1, v1]), np.array([0.0, tof]), MU, rtol=1e-13, atol=1e-13
    )[-1]
    relative = float(np.linalg.norm(arrival[:3] - _MULTIREV_R2)) / float(
        np.linalg.norm(_MULTIREV_R2)
    )
    assert relative < 1e-9, f"{branch} {revolutions}-rev arc missed by {relative:.3e} relative"


@pytest.mark.unit
@pytest.mark.parametrize("revolutions", [1, 2, 3])
def test_the_multi_revolution_arc_really_completes_that_many_revolutions(revolutions):
    """Check the *count*, not just that some arc reaches the target.

    Arriving at the right place at the right time is necessary but not sufficient: the whole
    point of ``revolutions=N`` is that the vehicle goes round N times on the way. The transfer
    orbit's own period is known in closed form from the returned velocity, so the number of
    periods elapsed must fall between N and N+1. This is what distinguishes the requested
    branch of a genuinely multi-valued problem from any other arc that happens to fit.
    """
    tof = 1.5 * minimum_multirev_time_s(_MULTIREV_R1, _MULTIREV_R2, MU, revolutions=revolutions)
    v1, _ = solve_lambert(_MULTIREV_R1, _MULTIREV_R2, tof, MU, revolutions=revolutions)

    energy = specific_energy_j_kg(np.concatenate([_MULTIREV_R1, v1]), MU)
    semi_major_axis = -MU / (2.0 * energy)
    laps = tof / orbital_period_s(semi_major_axis, MU)
    assert revolutions <= laps <= revolutions + 1, (
        f"asked for {revolutions} revolutions but the arc covers {laps:.4f} transfer periods"
    )


@pytest.mark.unit
def test_the_two_multi_revolution_branches_are_different_solutions():
    """Complement test: ``branch`` must select, not decorate.

    Both branches solve the same boundary value problem, so a solver that ignored ``branch``
    would still pass the propagation test above for both values. They are distinguished here
    by semi-major axis: the low-``z`` branch is the larger, slower-sweeping ellipse. Measured
    for this geometry at 1.3x the minimum time: a = 9.59e6 m against 7.63e6 m, and the
    departure velocities differ by 5.29e3 m/s.
    """
    tof = 1.3 * minimum_multirev_time_s(_MULTIREV_R1, _MULTIREV_R2, MU, revolutions=1)
    v_low, _ = solve_lambert(_MULTIREV_R1, _MULTIREV_R2, tof, MU, revolutions=1, branch="low")
    v_high, _ = solve_lambert(_MULTIREV_R1, _MULTIREV_R2, tof, MU, revolutions=1, branch="high")

    assert float(np.linalg.norm(v_low - v_high)) > 1.0e3

    a_low = -MU / (2.0 * specific_energy_j_kg(np.concatenate([_MULTIREV_R1, v_low]), MU))
    a_high = -MU / (2.0 * specific_energy_j_kg(np.concatenate([_MULTIREV_R1, v_high]), MU))
    assert a_low > a_high, (
        f"the low-z branch should be the larger ellipse: a_low={a_low:.4e} m, a_high={a_high:.4e} m"
    )


