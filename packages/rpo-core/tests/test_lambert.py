@pytest.mark.unit
def test_a_tolerance_below_the_arithmetic_noise_floor_raises_rather_than_pretending():
    """Asking for a residual the double-precision time equation cannot resolve must fail.

    This is a different refusal path from running out of iterations: here the bracket has
    collapsed onto adjacent floats and the answer is as good as double precision allows, but
    it still does not meet what was asked for. Reporting that is the whole contract.

    The case matters. For an exactly circular quarter orbit the root is representable and the
    residual comes out at exactly zero, so *any* tolerance is met -- correctly. The 28.8-degree
    circular arc used here has a root that is not exactly representable, and 15 of the 20
    cases in ``_PROPAGATION_CASES`` behave the same way at 1e-16 and below.

    The refused answer is checked to be numerically excellent regardless: the point is that
    "very close" is reported as a failure to meet the stated tolerance rather than passed off
    as success.
    """
    r1, r2, tof, _ = _endpoints(0.0, 0.08)
    with pytest.raises(LambertConvergenceError, match="residual") as excinfo:
        solve_lambert(r1, r2, tof, MU, time_rtol=1e-18)
    assert abs(excinfo.value.residual_s) > 1e-18 * tof
    assert abs(excinfo.value.residual_s) < 1e-9, (
        "the refused iterate should be numerically excellent -- the refusal is about the "
        "requested tolerance being unreachable, not about the answer being bad"
    )


