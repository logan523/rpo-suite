@pytest.mark.unit
def test_the_root_solve_converges_inside_a_measured_iteration_budget():
    """Pin the *cost* of convergence, not just the fact of it.

    ``max_iterations`` is the only handle the public API gives on how hard the solver worked,
    and running the whole sweep against a tight cap turns it into an assertion: if the
    iteration count regresses, this raises.

    That matters because the root solve can degrade silently. The Illinois modification of
    regula falsi must halve the retained endpoint's function value only when the *same*
    endpoint is retained twice running; applying it on every step instead corrupts both
    stored values symmetrically and collapses the method to plain bisection. Everything still
    converges to the same answer, every accuracy test in this file still passes, and the cost
    goes from 4-13 iterations to 30-41. Nothing else here would notice.

    Measured: 7 to 9 iterations for the single-revolution sweep and 8 to 13 for the
    multi-revolution branches. A cap of 20 is comfortable headroom over 13 while sitting well
    below the 30 that the degraded iteration needs.
    """
    for eccentricity, fraction in _PROPAGATION_CASES:
        r1, r2, tof, _ = _endpoints(eccentricity, fraction)
        solve_lambert(r1, r2, tof, MU, max_iterations=20)

    for revolutions in (1, 2, 3):
        tof_min = minimum_multirev_time_s(_MULTIREV_R1, _MULTIREV_R2, MU, revolutions=revolutions)
        for factor in (1.05, 1.5, 2.5):
            for branch in ("low", "high"):
                solve_lambert(
                    _MULTIREV_R1,
                    _MULTIREV_R2,
                    factor * tof_min,
                    MU,
                    revolutions=revolutions,
                    branch=branch,
                    max_iterations=20,
                )


