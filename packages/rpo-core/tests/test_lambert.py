@pytest.mark.integration
def test_prograde_and_retrograde_are_genuinely_different_transfers():
    """Complement test: prove ``prograde`` changes the answer, and both answers are valid.

    A flag that is read but never used would leave every other test in this file passing.
    Both solutions are checked against the propagator, so this is not merely "the numbers
    differ" -- they are two distinct correct arcs, in planes with opposite ``h_z``.
    """
    r1 = np.array([A_LEO_M, 0.0, 0.0])
    r2 = np.array([0.0, 0.9 * A_LEO_M, 0.3 * A_LEO_M])
    tof = 0.30 * PERIOD_S

    v_pro, _ = solve_lambert(r1, r2, tof, MU, prograde=True)
    v_retro, _ = solve_lambert(r1, r2, tof, MU, prograde=False)

    separation = float(np.linalg.norm(v_pro - v_retro))
    assert separation > 1.0e3, f"prograde and retrograde differ by only {separation:.3e} m/s"

    h_pro = float(np.cross(r1, v_pro)[2])
    h_retro = float(np.cross(r1, v_retro)[2])
    assert h_pro > 0.0 and h_retro < 0.0, (
        f"direction convention violated: h_z is {h_pro:.3e} prograde, {h_retro:.3e} retrograde"
    )

    for velocity in (v_pro, v_retro):
        arrival = propagate_two_body(np.concatenate([r1, velocity]), np.array([0.0, tof]), MU)[-1]
        assert float(np.linalg.norm(arrival[:3] - r2)) / float(np.linalg.norm(r2)) < 1e-9


