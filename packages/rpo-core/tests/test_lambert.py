@pytest.mark.unit
def test_the_solver_works_for_a_non_earth_central_body():
    """Nothing in the module may assume Earth; the only scale is ``mu``.

    Scaling ``mu`` by k and lengths by 1 scales times by 1/sqrt(k), so solving the scaled
    problem at the scaled time must give velocities scaled by sqrt(k). Checked against the
    Sun's gravitational parameter to make the scale ratio large.
    """
    mu_sun = 1.32712440018e20
    ratio = mu_sun / MU
    tof = 0.25 * PERIOD_S / math.sqrt(ratio)
    v_earth, _ = solve_lambert(R1_LEO, R2_LEO_QUARTER, 0.25 * PERIOD_S, MU)
    v_sun, _ = solve_lambert(R1_LEO, R2_LEO_QUARTER, tof, mu_sun)
    # atol is needed because the radial component of a circular arc is a numerical zero
    # (~1e-9 m/s against a 4.4e6 m/s speed); comparing that relatively compares noise.
    np.testing.assert_allclose(v_sun, v_earth * math.sqrt(ratio), rtol=1e-10, atol=1e-6)
