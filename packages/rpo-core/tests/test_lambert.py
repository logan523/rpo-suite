@pytest.mark.unit
@pytest.mark.parametrize(("eccentricity", "period_fraction"), _PROPAGATION_CASES)
def test_energy_and_angular_momentum_agree_at_the_two_endpoints(eccentricity, period_fraction):
    """The returned pair must describe one conic, not two unrelated velocities.

    Measured worst relative disagreement 2.9e-15 in energy and 1.3e-16 in angular momentum;
    1e-12 is three decades of headroom and still far tighter than any inconsistency a real
    error would produce.
    """
    r1, r2, tof, _ = _endpoints(eccentricity, period_fraction)
    v1, v2 = solve_lambert(r1, r2, tof, MU)

    energy_1 = specific_energy_j_kg(np.concatenate([r1, v1]), MU)
    energy_2 = specific_energy_j_kg(np.concatenate([r2, v2]), MU)
    assert abs(energy_1 - energy_2) / abs(energy_1) < 1e-12

    h1 = specific_angular_momentum(np.concatenate([r1, v1]))
    h2 = specific_angular_momentum(np.concatenate([r2, v2]))
    assert float(np.linalg.norm(h1 - h2)) / float(np.linalg.norm(h1)) < 1e-12


@pytest.mark.unit
def test_swapping_the_endpoints_gives_the_time_reversed_solution():
    """Time reversal: solve backwards and the velocities negate exactly.

    The direction flag must flip as well, and that is the point of the test. Negating both
    velocities reverses the specific angular momentum, so the time-reversed arc has the
    opposite sign of ``h_z`` -- a prograde transfer run backwards is a retrograde one. A
    solver that ignored ``prograde`` entirely would fail this; so would one that flipped it
    in the wrong place.
    """
    r1, r2, tof, _ = _endpoints(0.30, 0.37)
    v1, v2 = solve_lambert(r1, r2, tof, MU, prograde=True)
    w1, w2 = solve_lambert(r2, r1, tof, MU, prograde=False)

    np.testing.assert_allclose(w1, -v2, rtol=1e-12, atol=1e-9)
    np.testing.assert_allclose(w2, -v1, rtol=1e-12, atol=1e-9)


@pytest.mark.unit
def test_reversing_without_flipping_the_direction_gives_a_different_arc():
    """Complement to the test above: the direction flip is load-bearing, not decorative."""
    r1, r2, tof, _ = _endpoints(0.30, 0.37)
    _, v2 = solve_lambert(r1, r2, tof, MU, prograde=True)
    w1, _ = solve_lambert(r2, r1, tof, MU, prograde=True)
    assert float(np.linalg.norm(w1 - (-v2))) > 1.0e3, (
        "keeping prograde=True on the reversed problem produced the time-reversed answer, "
        "which means the direction convention is not being applied"
    )


