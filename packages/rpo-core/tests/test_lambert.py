"""Lambert's problem: verification by independent propagation, closed forms, and failures.

The load-bearing test in this file is
:func:`test_lambert_velocity_propagates_onto_the_target_position`. Everything else supports
it. ``rpo_core.propagate.propagate_two_body`` is validated separately (energy and angular
momentum conserved to better than 1e-10 relative over ten orbits, monotone convergence under
tolerance tightening), and it shares no code with ``rpo_core.lambert``: it integrates the
equation of motion where Lambert solves a boundary value problem in closed form plus one
scalar root. Feeding Lambert's departure velocity into that integrator and asking where it
ends up is therefore an external oracle, not a restatement of the solver's own arithmetic.

Numbers quoted in tolerance comments were measured on this machine before the bound was
chosen; the headroom is stated in each case.
"""

import math

import numpy as np
import pytest
from rpo_core.constants import (
    MU_EARTH_M3_S2,
    R_EARTH_EQUATORIAL_M,
    orbital_period_s,
)
from rpo_core.exceptions import DegenerateGeometryError, InfeasibleTransferError
from rpo_core.lambert import (
    LambertConvergenceError,
    minimum_multirev_time_s,
    solve_lambert,
    stumpff_c,
    stumpff_s,
    transfer_angle_rad,
)
from rpo_core.propagate import (
    propagate_two_body,
    specific_angular_momentum,
    specific_energy_j_kg,
)

MU = MU_EARTH_M3_S2
A_LEO_M = R_EARTH_EQUATORIAL_M + 420.0e3
PERIOD_S = orbital_period_s(A_LEO_M)
V_CIRCULAR = math.sqrt(MU / A_LEO_M)

R1_LEO = np.array([A_LEO_M, 0.0, 0.0])
R2_LEO_QUARTER = np.array([0.0, A_LEO_M, 0.0])


def _state_at_periapsis(eccentricity: float) -> tuple[np.ndarray, float]:
    """Return an inertial state at periapsis radius ``A_LEO_M`` and its orbital period."""
    speed = math.sqrt(MU * (1.0 + eccentricity) / A_LEO_M)
    state = np.array([A_LEO_M, 0.0, 0.0, 0.0, speed, 0.0])
    return state, orbital_period_s(A_LEO_M / (1.0 - eccentricity))


def _endpoints(eccentricity: float, period_fraction: float, **kwargs: float) -> tuple:
    """Propagate a reference arc and return ``(r1, r2, tof, truth_state_at_r2)``.

    The reference arc is generated by the integrator, so ``(r1, r2, tof)`` is guaranteed to
    be a triple that a real two-body trajectory actually connects. Handing Lambert a
    geometrically arbitrary triple would test far less: the solver would still return an
    answer, but there would be no independently known velocity to compare against.
    """
    state, period = _state_at_periapsis(eccentricity)
    tof = period_fraction * period
    arc = propagate_two_body(state, np.array([0.0, tof]), MU, **kwargs)
    return arc[0][:3], arc[-1][:3], tof, arc[-1]


# Spread of transfer angles: 28.8 deg and 38.6 deg are well below 180; 216, 253, 290 and 306
# are well above; 90, 71.7, 106.9 and 122.3 straddle the right angle. Eccentricity runs from
# circular to 0.75 so the arcs are not all near-circular, where a sign error in the geometry
# constant A would be hidden by r1 == r2.
_PROPAGATION_CASES = [
    (ecc, frac) for ecc in (0.0, 0.15, 0.45, 0.75) for frac in (0.08, 0.25, 0.40, 0.60, 0.85)
]


@pytest.mark.integration
@pytest.mark.parametrize(("eccentricity", "period_fraction"), _PROPAGATION_CASES)
def test_lambert_velocity_propagates_onto_the_target_position(eccentricity, period_fraction):
    """The oracle test: fly the solved departure velocity and check where it lands.

    Bound set from measurement. Across these twenty cases the worst position residual is
    7.09e-4 m -- 2.40e-11 of the arrival radius -- at the package-default integrator
    tolerance of 1e-12. The assertion is made relative to the arrival radius because the
    cases span radii from 6.8e6 m to 4.8e7 m, and 1e-9 leaves roughly forty times headroom
    over the worst measured value while still being four decades tighter than any error a
    wrong branch, a wrong quadrant, or a dropped term could produce.
    """
    r1, r2, tof, _ = _endpoints(eccentricity, period_fraction)
    v1, _ = solve_lambert(r1, r2, tof, MU)

    arrival = propagate_two_body(np.concatenate([r1, v1]), np.array([0.0, tof]), MU)[-1]
    residual_m = float(np.linalg.norm(arrival[:3] - r2))
    relative = residual_m / float(np.linalg.norm(r2))
    assert relative < 1e-9, (
        f"propagating the Lambert v1 for {tof:.3f} s missed r2 by {residual_m:.6e} m "
        f"({relative:.3e} relative)"
    )


@pytest.mark.integration
@pytest.mark.parametrize(("eccentricity", "period_fraction"), _PROPAGATION_CASES)
def test_lambert_arrival_velocity_matches_the_propagated_arrival_velocity(
    eccentricity, period_fraction
):
    """``v2`` must equal the velocity the integrator reports on arrival, not just ``v1``.

    Without this, a solver that got ``v1`` right and ``v2`` from a mistyped Lagrange
    coefficient would pass every other test in the file.
    """
    r1, r2, tof, truth = _endpoints(eccentricity, period_fraction)
    _, v2 = solve_lambert(r1, r2, tof, MU)
    error = float(np.linalg.norm(v2 - truth[3:]))
    speed = float(np.linalg.norm(truth[3:]))
    assert error / speed < 1e-9, f"v2 off by {error:.3e} m/s on a {speed:.3f} m/s arrival"


@pytest.mark.integration
def test_propagate_back_residual_shrinks_as_the_integrator_tightens():
    """Show the residual above is the *integrator's* error, not Lambert's.

    A single threshold cannot distinguish "Lambert is accurate" from "Lambert is wrong by
    less than a loose bound". If the miss distance is dominated by integration error it must
    fall when the integrator tolerance falls, and Lambert's own contribution is whatever is
    left at the tightest setting. Measured: 2.58e-2, 3.85e-3, 7.49e-4, 1.13e-4, 8.73e-6 m at
    rtol = 1e-9 ... 1e-13, i.e. a clean three-and-a-half decade descent tracking the
    integrator, which puts Lambert's own error below 1e-5 m on a 1.8e7 m arc.
    """
    residuals = []
    for tol in (1e-9, 1e-10, 1e-11, 1e-12, 1e-13):
        r1, r2, tof, _ = _endpoints(0.45, 0.60, rtol=tol, atol=tol)
        v1, _ = solve_lambert(r1, r2, tof, MU)
        arrival = propagate_two_body(
            np.concatenate([r1, v1]), np.array([0.0, tof]), MU, rtol=tol, atol=tol
        )[-1]
        residuals.append(float(np.linalg.norm(arrival[:3] - r2)))

    assert all(residuals[i] > residuals[i + 1] for i in range(len(residuals) - 1)), (
        f"miss distance did not shrink monotonically with integrator tolerance: {residuals}"
    )
    assert residuals[-1] < 1e-4, f"residual floor {residuals[-1]:.3e} m is above 0.1 mm"


