@pytest.mark.unit
@pytest.mark.parametrize("z", [-40.0, -12.0, -1.5, -1.0001, 1.0001, 2.5, 20.0, 39.0, 150.0])
def test_stumpff_series_and_closed_forms_agree_across_the_switchover(z):
    """Two independent algorithms for the same function must meet at the threshold.

    Outside ``|z| <= 1`` the module uses the elementary closed form; inside it uses the power
    series. Evaluating the closed form here and comparing catches a wrong factorial offset or
    a wrong branch in either. Measured agreement is at or below 2.3e-16 relative.
    """
    if z > 0.0:
        root = math.sqrt(z)
        expected_c = (1.0 - math.cos(root)) / z
        expected_s = (root - math.sin(root)) / root**3
    else:
        root = math.sqrt(-z)
        expected_c = (math.cosh(root) - 1.0) / (-z)
        expected_s = (math.sinh(root) - root) / root**3
    assert stumpff_c(z) == pytest.approx(expected_c, rel=1e-14)
    assert stumpff_s(z) == pytest.approx(expected_s, rel=1e-14)


@pytest.mark.unit
def test_stumpff_functions_take_their_parabolic_values_at_zero():
    """``C(0) = 1/2`` and ``S(0) = 1/6``: the leading terms of the defining series."""
    assert stumpff_c(0.0) == pytest.approx(0.5, rel=1e-15)
    assert stumpff_s(0.0) == pytest.approx(1.0 / 6.0, rel=1e-15)


@pytest.mark.unit
def test_stumpff_functions_at_the_one_revolution_singularity():
    """At ``z = 4*pi**2`` (one full revolution in eccentric anomaly) ``C`` vanishes.

    This is the analytic reason ``dt(z) -> infinity`` at the ends of every multi-revolution
    interval, so it is worth pinning independently of the solver that relies on it.
    """
    z = 4.0 * math.pi**2
    assert abs(stumpff_c(z)) < 1e-15
    assert stumpff_s(z) == pytest.approx(1.0 / (4.0 * math.pi**2), rel=1e-12)


@pytest.mark.unit
def test_stumpff_functions_are_continuous_across_the_series_threshold():
    """No visible seam where the implementation switches algorithm."""
    for side in (-1.0, 1.0):
        below = stumpff_c(side * (1.0 - 1e-12))
        above = stumpff_c(side * (1.0 + 1e-12))
        assert below == pytest.approx(above, rel=1e-14)
        assert stumpff_s(side * (1.0 - 1e-12)) == pytest.approx(
            stumpff_s(side * (1.0 + 1e-12)), rel=1e-14
        )


