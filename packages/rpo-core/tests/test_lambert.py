@pytest.mark.unit
def test_quarter_orbit_of_a_circular_orbit_returns_the_circular_speed():
    """Analytic limiting case: the arc *is* the circular orbit, so both speeds are v_circ.

    Measured error 9.1e-13 m/s on a 7660 m/s speed; the 1e-9 bound is three decades of
    headroom.
    """
    v1, v2 = solve_lambert(R1_LEO, R2_LEO_QUARTER, 0.25 * PERIOD_S, MU)
    assert float(np.linalg.norm(v1)) == pytest.approx(V_CIRCULAR, abs=1e-9)
    assert float(np.linalg.norm(v2)) == pytest.approx(V_CIRCULAR, abs=1e-9)
    # The velocity must also point the right way: purely along-track at the start.
    np.testing.assert_allclose(v1, [0.0, V_CIRCULAR, 0.0], atol=1e-6)


@pytest.mark.unit
def test_hohmann_delta_v_is_recovered_as_the_transfer_angle_approaches_180_degrees():
    r"""The 180-degree transfer is the Hohmann transfer, approached as a limit.

    A Hohmann transfer between coplanar circular orbits is a 180-degree Lambert problem with
    the time of flight equal to half the transfer-ellipse period -- which is exactly the
    degenerate case this module refuses to solve, because at :math:`\Delta\theta = \pi` the
    two position vectors are collinear and the transfer plane is undefined. So it is
    approached from below: 178, 179, 179.9 and 179.99 degrees, asserting that the error
    against the closed-form Hohmann delta-v *shrinks monotonically*, which no single
    hand-picked angle could demonstrate.

    Measured total delta-v error: 3.80, 9.49e-1, 9.48e-3, 5.48e-5 m/s against a 3406.264 m/s
    Hohmann total. The 1e-4 m/s bound at 179.99 degrees is about a factor of two of headroom
    -- deliberately tight, because past this point the limit stops improving (see
    ``test_the_transfer_plane_becomes_ill_conditioned_near_180_degrees``) and a looser bound
    would hide that.
    """
    r_inner = R_EARTH_EQUATORIAL_M + 400.0e3
    r_outer = R_EARTH_EQUATORIAL_M + 20000.0e3
    a_transfer = 0.5 * (r_inner + r_outer)
    tof = math.pi * math.sqrt(a_transfer**3 / MU)

    v_circ_inner = math.sqrt(MU / r_inner)
    v_circ_outer = math.sqrt(MU / r_outer)
    dv1_closed = v_circ_inner * (math.sqrt(2.0 * r_outer / (r_inner + r_outer)) - 1.0)
    dv2_closed = v_circ_outer * (1.0 - math.sqrt(2.0 * r_inner / (r_inner + r_outer)))
    total_closed = dv1_closed + dv2_closed

    errors = []
    for degrees in (178.0, 179.0, 179.9, 179.99):
        angle = math.radians(degrees)
        r1 = np.array([r_inner, 0.0, 0.0])
        r2 = r_outer * np.array([math.cos(angle), math.sin(angle), 0.0])
        v1, v2 = solve_lambert(r1, r2, tof, MU)

        departure = float(np.linalg.norm(v1 - np.array([0.0, v_circ_inner, 0.0])))
        arrival_circular = v_circ_outer * np.cross([0.0, 0.0, 1.0], r2 / np.linalg.norm(r2))
        arrival = float(np.linalg.norm(arrival_circular - v2))
        errors.append(abs(departure + arrival - total_closed))

    assert all(errors[i] > errors[i + 1] for i in range(len(errors) - 1)), (
        f"Hohmann agreement did not improve monotonically towards 180 deg: {errors}"
    )
    assert errors[-1] < 1e-4, (
        f"at 179.99 deg the total delta-v is off the closed-form Hohmann value by "
        f"{errors[-1]:.3e} m/s (total {total_closed:.6f} m/s)"
    )


