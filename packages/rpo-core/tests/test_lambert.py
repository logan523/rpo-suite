@pytest.mark.unit
def test_the_transfer_plane_becomes_ill_conditioned_near_180_degrees():
    """Complement test for the antiparallel guard: the degeneracy is real, not conservative.

    The guard rejects the exactly-collinear case. This shows *why*, and that the guard is
    sitting on a genuine cliff rather than an arbitrary line: displacing the arrival point by
    one metre out of plane -- on a vector of 2.6e7 m -- swings the resulting orbit normal by
    9e-6 degrees at a 150-degree transfer and by 2.5 degrees at 179.9999 degrees, a
    sensitivity amplification of about 280000.

    It also records a limitation honestly: the default ``collinear_tol`` of 1e-8 on
    ``|sin(dtheta)|`` guards *definedness*, not accuracy. Answers returned between roughly
    179.999 degrees and the guard are progressively ill-conditioned, and a caller who needs a
    trustworthy plane there should tighten ``collinear_tol`` themselves.
    """
    r_inner = R_EARTH_EQUATORIAL_M + 400.0e3
    r_outer = R_EARTH_EQUATORIAL_M + 20000.0e3
    tof = math.pi * math.sqrt((0.5 * (r_inner + r_outer)) ** 3 / MU)
    r1 = np.array([r_inner, 0.0, 0.0])

    swings = []
    for degrees in (150.0, 179.9999):
        angle = math.radians(degrees)
        base = r_outer * np.array([math.cos(angle), math.sin(angle), 0.0])
        normals = []
        for offset in (-1.0, 1.0):
            v1, _ = solve_lambert(r1, base + np.array([0.0, 0.0, offset]), tof, MU)
            h = np.cross(r1, v1)
            normals.append(h / np.linalg.norm(h))
        cosine = min(1.0, max(-1.0, float(np.dot(normals[0], normals[1]))))
        swings.append(math.degrees(math.acos(cosine)))

    assert swings[0] < 1e-3, f"a 150-degree transfer should be well conditioned: {swings[0]}"
    assert swings[1] > 1.0, (
        f"the near-180-degree plane should be violently sensitive, but a 1 m perturbation "
        f"moved the orbit normal by only {swings[1]:.3e} degrees"
    )


