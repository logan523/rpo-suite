@pytest.mark.unit
def test_short_times_of_flight_give_hyperbolic_arcs_and_long_ones_elliptic():
    """The formulation is meant to cross conic types without branching; check that it does.

    A quarter-turn in a tenth of an orbital period cannot be done on a bound orbit, so the
    specific energy must come out positive. This is also a complement test for the universal
    variable: a solver that silently clamped ``z >= 0`` would return an elliptic arc here and
    quietly miss the target.
    """
    energies = []
    for fraction in (0.05, 0.10, 0.25, 0.50, 0.90):
        v1, _ = solve_lambert(R1_LEO, R2_LEO_QUARTER, fraction * PERIOD_S, MU)
        energies.append(specific_energy_j_kg(np.concatenate([R1_LEO, v1]), MU))
    assert energies[0] > 0.0 and energies[1] > 0.0, f"short arcs are not hyperbolic: {energies}"
    assert all(e < 0.0 for e in energies[2:]), f"long arcs are not elliptic: {energies}"


